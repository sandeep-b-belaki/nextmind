const dicts: Record<Lang, Dict> = { kn, en, hi };

export function t(lang: Lang, key: string): string {
  return dicts[lang]?.[key] ?? dicts.en[key] ?? key;
}

export function tr(lang: Lang, knText: string, hiText: string, enText: string): string {
  if (lang === 'kn') return knText;
  if (lang === 'hi') return hiText;
  return enText;
}

export function content(lang: Lang, kn: string, en: string, hi?: string | null): string {
  if (lang === 'kn') return kn;
  if (lang === 'hi') return hi || en;
  return en;
}

export function pick<T extends { [k: string]: unknown }>(obj: T, lang: Lang, suffix: string): string {
  const val = obj[`${suffix}_${lang}`];
  return (val ?? obj[`${suffix}_kn`] ?? '') as string;
}
